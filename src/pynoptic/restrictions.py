_BY_ID: dict[str, Restriction] = {r.id: r for r in CATALOG}

SEMGREP_SPECS: dict[str, SemgrepSpec] = {
    r.id: r.semgrep for r in CATALOG if r.semgrep is not None
}
AST_SPECS: dict[str, AstSpec] = {
    r.id: AstSpec(r.ast) for r in CATALOG if r.ast is not None
}


def restrictions() -> tuple[Restriction, ...]:
    """All 220 restrictions, in catalog order."""
    return CATALOG


def get_restriction(restriction_id: str) -> Restriction:
    """Look up a single restriction by id."""
    return _BY_ID[restriction_id]


def restrictions_at_least(exercise_level: Level | int | str) -> tuple[Restriction, ...]:
    """Restrictions whose scope is at or above exercise_level (i.e. NCCs)."""
    level = Level.parse(exercise_level)
    return tuple(r for r in CATALOG if r.scope >= level)


def restrictions_by_tool(tool: Tool | str) -> tuple[Restriction, ...]:
    """Restrictions assigned to a given detection tool."""
    wanted = Tool(tool)
    if isinstance(tool, Tool):
        wanted = tool
    return tuple(r for r in CATALOG if r.tool is wanted)


def all_covered_ids() -> set[str]:
    """Every restriction id reachable by at least one detector.

    Returns:
        - The set of covered restriction ids.
    """
    return {
        r.id
        for r in CATALOG
        if r.semgrep or r.ast or r.candidate or r.dynamic
    }

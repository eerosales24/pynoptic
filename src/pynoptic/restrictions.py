"""

* id          unique identifier, prefixed with R
* restriction short name of what must not be used
* scope       last level at which the construct is off-limits
* tool        detector responsible for the restriction
* technique   how that detector identifies it
* note        why it needs that technique and what detection may miss
* semgrep     the Semgrep rule, when detected statically by Semgrep
* ast         the ast detector label, when detected by the ast engine
* candidate   the Semgrep candidate for a statically ambiguous construct
* conclusive  whether a candidate is already definitive statically
* dynamic     the runtime triggers that classify the construct
"""

from __future__ import annotations

from .models import AstSpec, DynamicMatch, Level, Restriction, SemgrepSpec, Tool


def _sg(pattern: str) -> SemgrepSpec:
    """Build a spec from a single Semgrep pattern."""
    return SemgrepSpec(pattern=pattern)


def _either(*patterns: str) -> SemgrepSpec:
    """Build a spec that matches any of several patterns."""
    return SemgrepSpec(either=tuple(patterns))


def _and(*patterns: dict[str, object]) -> SemgrepSpec:
    """Build a spec that requires several Semgrep clauses."""
    return SemgrepSpec(patterns=tuple(patterns))


def _regex(pattern: str) -> SemgrepSpec:
    """Build a lexical spec matched with pattern-regex."""
    return SemgrepSpec(regex=pattern)


def _funcs(*names: str) -> SemgrepSpec:
    """Build a spec matching calls to any of several functions."""
    return _either(*(f"{name}(...)" for name in names))


def _methods(*names: str) -> SemgrepSpec:
    """Build a spec matching calls to any of several methods."""
    return _either(*(f"$X.{name}(...)" for name in names))


def _imports(*modules: str) -> SemgrepSpec:
    """Build a spec matching imports of any of several modules."""
    patterns: list[str] = []
    for module in modules:
        patterns.append(f"import {module}")
        patterns.append(f"from {module} import $X")
        root = module.split(".")[0]
        if root != module:
            patterns.append(f"from {root} import $X")
    return _either(*patterns)


